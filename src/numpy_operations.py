print("\n=== Views Versus Copies")
base = np.arange(6)
print(f"{base=}")
print("Basic slicing normally creates a view sharing the original data")
view = base[1:5]
print(f"{view=}, {np.shares_memory(base, view)=}")
print("Changing the view changes the original array")
view[0] = 99
print(f"{base=}, {view=}")
print("Advanced integer indexing creates a copy")
fancy_copy = base[[1, 3, 5]]
print(f"{fancy_copy=}, {np.shares_memory(base, fancy_copy)=}")
print("Changing this copy does not change the original array")
fancy_copy[0] = -1
print(f"{base=}, {fancy_copy=}")
print("Boolean indexing also creates a copy")
boolean_copy = base[base > 3]
print(f"{boolean_copy=}, {np.shares_memory(base, boolean_copy)=}")
print("Make an explicit independent copy of a slice")
explicit_copy = base[1:4].copy()
print(f"{explicit_copy=}, {np.shares_memory(base, explicit_copy)=}")

print("\n=== Indexed Assignment")
z = np.arange(10)
print(f"{z=}")
print("Assign to a single indexed element")
z[0] = 50
print(f"{z=}")
print("Assign a scalar to every element in a slice")
z[2:7:2] = 99
print(f"{z=}")
print("Assign a sequence of values to selected indices")
z[[1, 3, 5]] = [11, 33, 55]
print(f"{z=}")
print("Assign to all entries meeting a Boolean condition")
z[z > 50] = -1
print(f"{z=}")
print("Repeated integer indices in assignment are not accumulated")
z[[0, 0]] = [7, 8]
print(f"{z=}")
print("Use np.add.at when repeated indices should accumulate")
np.add.at(z, [0, 0], 1)
print(f"{z=}")

